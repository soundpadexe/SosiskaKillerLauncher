//! Two languages: Ukrainian and Toki Pona (a ~130-word constructed language).
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(from = "String")]
pub enum Lang {
    #[default]
    Uk,
    Tok,
}

/// Unknown/legacy values (old "En"/"Ru" configs) fall back to Ukrainian instead of
/// invalidating the whole settings file.
impl From<String> for Lang {
    fn from(s: String) -> Self {
        if s == "Tok" { Lang::Tok } else { Lang::Uk }
    }
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::Uk, Lang::Tok];

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Uk => "Українська",
            Lang::Tok => "toki pona",
        }
    }
}

